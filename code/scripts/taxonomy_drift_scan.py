"""
taxonomy_drift_scan.py — generalized drift-detection safety net for the
hardcoded keyword->canonical-target-string structures across the 3 persona
files that the 2026-11 hardcoded-logic audit's full-codebase inventory found
(15 total; this script covers the structures below that have a real corpus
field to check against — see "deliberately not included" below for the rest).

Background: see service/live_taxonomy.py's module docstring for the full
rationale. Short version: this bot was built against a human-curated Google
Sheet (naturally stable taxonomy); the corpus has since shifted to primarily
raw PDF uploads where each document's taxonomy fields are independently
free-generated by an LLM with zero existing-vocabulary constraint. Any
hardcoded Python literal asserting "X is a valid corpus value right now" can
silently drift the moment a document is re-ingested with different wording.
_KW_OVERRIDE_LICENSE_TYPES already had its own one-off startup check
(persona_supervisor.py's _validate_license_types_at_startup — found 8/9
entries drifted the first time anyone ran it). This script generalizes that
same check into a hand-maintained registry covering the OTHER structures of
the same shape found by this session's inventory.

Like filter_guard_static_scan.py, this is a heuristic TEXT scan over the raw
source (regex over file contents), not AST analysis — each registry entry
below hand-pins the exact anchor regex and value-extraction regex for ONE
structure, because each has a different literal shape (dict / list-of-tuples
/ frozenset / nested frozenset-in-tuple) that no single generic extractor
parses reliably. Adding a NEW structure of this shape means adding one
STRUCTURES entry — copy whichever existing entry has the closest shape.

Extracted target strings are resolved against the live corpus via
service.live_taxonomy's own Tier-A resolver (resolve_candidate: exact ->
substring -> fuzzy @ 0.82), not raw equality — several of these structures
(e.g. _MENU_FALLBACK_TOPICS) are deliberately paraphrased display text, not
verbatim field values, so exact-equality would spuriously flag every entry.
Only a hint that doesn't even fuzzy-resolve ("empty") is flagged; "ambiguous"
(multiple close live values, unclear which) is treated as present-but-messy,
not missing, and not flagged — that's a different, lower-urgency problem than
what this script exists to catch.

Deliberately NOT included (checked, genuinely not applicable):
  - _BANK_ID_PATTERNS (persona_supervisor.py): tags ("scb", "kbank", ...) are
    internal labels for a bank-switch check, never a corpus field value —
    nothing to resolve against.
  - _KNOWN_TOPIC_GROUPS (persona_academic.py): topic_group is an LLM-computed
    runtime grouping, never stored in Chroma/ES metadata (see that file's own
    comment on _SYNTHETIC_OP_ROOTS making the same point about operation_
    group) — no live field exists to check it against.
  - _MULTI_TOPIC_PATTERNS (persona_academic.py): targets are free-text
    retrieval sub-queries ("การจดทะเบียนภาษีมูลค่าเพิ่ม VAT เงื่อนไข..."), not
    canonical field values — there's nothing to resolve.
  - _SYNTHETIC_OP_ROOTS (persona_academic.py): targets are bare verb-root
    substrings ("ยื่น", "ขอ") matched loosely against operation text by
    design, not exact field values.
Already covered elsewhere, not duplicated here:
  - _KW_OVERRIDE_LICENSE_TYPES / _SUPERVISOR_KW_OVERRIDE: persona_supervisor.
    py's _validate_license_types_at_startup() already checks this every boot.
  - _MULTI_TOPIC_LICENSE_KEYWORDS / _RARE_LT_PATTERNS: migrated this session
    to resolve dynamically via live_taxonomy at query time instead of
    trusting a hardcoded target string — nothing static left to drift-check.

Usage:
    PYTHONPATH="$PWD/code" python3 code/scripts/taxonomy_drift_scan.py
Exit code: 0 if no WARNs, 1 if any WARN found (suitable for a CI gate once
the current baseline is clean). Also callable in-process (see
check_drift(vectorstore)) — persona_supervisor.py's
_validate_license_types_at_startup wires this in so every boot gets the same
visibility for free, not just a manual CLI run.
"""
from __future__ import annotations

import os
import re
import sys
from dataclasses import dataclass
from typing import Callable, List, Optional

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))


@dataclass
class StructureSpec:
    name: str
    file: str
    field: str  # corpus metadata field to resolve extracted values against
    severity: str  # "high" (feeds retrieval/filter logic) | "info" (display-only)
    anchor_re: "re.Pattern"
    value_re: "re.Pattern"
    note: str = ""


STRUCTURES: List[StructureSpec] = [
    StructureSpec(
        name="_AREA_SENSITIVE_LICENSES",
        file="code/model/persona_supervisor.py",
        field="license_type",
        severity="high",
        anchor_re=re.compile(r"_AREA_SENSITIVE_LICENSES:\s*frozenset\s*=\s*frozenset\(\{(.*?)\}\)", re.DOTALL),
        value_re=re.compile(r'"([^"]+)"'),
    ),
    StructureSpec(
        name="_BANK_DEPT_PATTERNS",
        file="code/model/persona_supervisor.py",
        field="department",
        severity="high",
        anchor_re=re.compile(r"_BANK_DEPT_PATTERNS:\s*List\[Tuple\]\s*=\s*\[(.*?)\n\s*\]", re.DOTALL),
        value_re=re.compile(r'\),\s*"([^"]+)"\)'),
    ),
    StructureSpec(
        name="_MENU_FALLBACK_TOPICS",
        file="code/model/persona_supervisor.py",
        field="main_topic",
        severity="info",
        note="curated display paraphrases, not verbatim field values — WARN here is a weaker signal than for 'high' entries",
        anchor_re=re.compile(r'_MENU_FALLBACK_TOPICS:\s*List\[str\]\s*=\s*list\(getattr\(conf,\s*"MENU_FALLBACK_TOPICS",\s*\[(.*?)\]\)\)', re.DOTALL),
        value_re=re.compile(r'"([^"]+)"'),
    ),
    StructureSpec(
        name="_RELATED_TOPIC_GROUPS",
        file="code/model/persona_practical.py",
        field="license_type",
        severity="high",
        anchor_re=re.compile(r"_RELATED_TOPIC_GROUPS:\s*list\s*=\s*\[(.*?)\n\]", re.DOTALL),
        # Only strings INSIDE a frozenset({...}) — not each group's trailing note string.
        value_re=re.compile(r'frozenset\(\{(.*?)\}\)', re.DOTALL),
        note="value_re yields each frozenset's inner text; strings extracted from that in a second pass (see _extract below)",
    ),
    StructureSpec(
        name="_LOCATION_SWITCH_MAP",
        file="code/model/persona_practical.py",
        field="location",
        severity="high",
        anchor_re=re.compile(r"_LOCATION_SWITCH_MAP\s*=\s*\[(.*?)\n\s*\]", re.DOTALL),
        value_re=re.compile(r',\s*"([^"]+)"\)'),
    ),
    StructureSpec(
        name="_RT_CANONICAL_MAP",
        file="code/model/persona_academic.py",
        field="registration_type",
        severity="high",
        anchor_re=re.compile(r"_RT_CANONICAL_MAP:\s*Dict\[str,\s*str\]\s*=\s*\{(.*?)\}", re.DOTALL),
        # Values only (the right side of "key": "value") — the canonical target,
        # not the known-drifted raw spelling on the left.
        value_re=re.compile(r':\s*"([^"]+)"'),
    ),
]


@dataclass
class DriftFinding:
    structure: str
    file: str
    field: str
    severity: str
    value: str


def _extract_values(spec: StructureSpec, source: str) -> List[str]:
    anchor_match = spec.anchor_re.search(source)
    if not anchor_match:
        return []
    block = anchor_match.group(1)

    if spec.name == "_RELATED_TOPIC_GROUPS":
        values: List[str] = []
        for fs_match in spec.value_re.finditer(block):
            values.extend(re.findall(r'"([^"]+)"', fs_match.group(1)))
        return values

    return spec.value_re.findall(block)


def check_drift(vectorstore, repo_root: Optional[str] = None) -> List[DriftFinding]:
    """Extract each registry entry's target strings from its file's source,
    resolve each against the live corpus (service.live_taxonomy), and return
    one DriftFinding per value that doesn't even fuzzy-resolve. Safe to call
    every boot — read-only source scan + the same cached live-corpus fetch
    live_taxonomy already uses elsewhere."""
    from service.live_taxonomy import get_live_values, resolve_candidate

    _repo_root = repo_root or os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    findings: List[DriftFinding] = []
    field_cache: dict = {}

    for spec in STRUCTURES:
        abs_path = os.path.join(_repo_root, spec.file)
        try:
            with open(abs_path, "r", encoding="utf-8") as f:
                source = f.read()
        except OSError:
            continue

        values = _extract_values(spec, source)
        if not values:
            continue

        if spec.field not in field_cache:
            field_cache[spec.field] = get_live_values(vectorstore, spec.field)
        live_values = field_cache[spec.field]
        if not live_values:
            continue  # field not fetchable right now — don't flag false drift

        seen: set = set()
        for value in values:
            if value in seen:
                continue
            seen.add(value)
            resolved, _kind = resolve_candidate(value, live_values)
            if resolved is None and _kind == "empty":
                findings.append(DriftFinding(spec.name, spec.file, spec.field, spec.severity, value))

    return findings


def _get_vectorstore_for_cli():
    import conf
    if getattr(conf, "USE_ELASTICSEARCH", False):
        from service.es_vector_store import get_retriever, get_vs_manager
    else:
        from service.local_vector_store import get_retriever, get_vs_manager
    get_retriever(fail_if_empty=False)
    return get_vs_manager().vectorstore


def main() -> int:
    vectorstore = _get_vectorstore_for_cli()
    findings = check_drift(vectorstore)

    print("=" * 78)
    print("TAXONOMY DRIFT SCAN")
    print("=" * 78)
    if not findings:
        print("No drift found across the checked structures.")
        return 0

    n_high = sum(1 for f in findings if f.severity == "high")
    n_info = sum(1 for f in findings if f.severity == "info")
    for f in findings:
        tag = "WARN" if f.severity == "high" else "info"
        print(f"  [{tag}] {f.structure} ({f.file}, field={f.field}): {f.value!r} not found in live corpus (even fuzzy)")

    print("-" * 78)
    print(f"{n_high} high-severity, {n_info} info-only drift finding(s).")
    if n_high:
        print("Review the WARN lines above — likely a renamed/removed corpus value a hardcoded structure still targets.")
    return 1 if n_high else 0


if __name__ == "__main__":
    sys.exit(main())
