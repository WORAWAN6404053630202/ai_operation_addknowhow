    _URL_CONTINUATION_RE = re.compile(r'^[a-zA-Z0-9._/\-?=&%+#@!~,;:]+')

    def _fix_line_wrapping(self, text: str) -> str:
        """Fix URL lines that LLM wrapped mid-path.
        Case 1: lone '- ' or '• ' bullet before a URL on the next line → join.
        Case 2: URL split mid-path across two lines → join.
        Does NOT touch Thai text — too risky to auto-join Thai sentences.
        """
        if not text:
            return text
        # Case 0: convert indented numbered sub-items to bullets
        # e.g. "   1. ระวางโทษ..." → "   • ระวางโทษ..."
        text = re.sub(r'(?m)^([ \t]{2,})\d+[).]\s+', r'\1• ', text)

        # Case 3: section header and first numbered item on the same line
        # e.g. "📋 ขั้นตอนการดำเนินการ 1. เข้าสู่ระบบ" → split before "1."
        text = re.sub(
            r'([\u2600-\u27BF\U0001F300-\U0001FFFF][^\n]*?[ก-๙])\s+(\d+[).]\s)',
            r'\1\n\2',
            text,
        )

        lines = text.split("\n")
        result = []
        i = 0
        while i < len(lines):
            line = lines[i]
            if i + 1 < len(lines):
                next_line = lines[i + 1]
                stripped_next = next_line.strip()
                # Case 1: lone bullet/dash with URL on next line e.g. "   - \nhttps://..."
                if re.match(r'^[\-•]\s*$', line.strip()) and stripped_next.startswith("http"):
                    result.append(line.rstrip() + " " + stripped_next)
                    i += 2
                    continue
                # Case 2: URL split mid-path — line ends with URL chars, next continues URL
                if (self._URL_TRAILING_RE.search(line) and
                        stripped_next and
                        self._URL_CONTINUATION_RE.match(stripped_next) and
                        not re.match(r'^[\u0E00-\u0E7F\s\-•*\d]', stripped_next)):
                    result.append(line.rstrip() + stripped_next)
                    i += 2
                    continue
            result.append(line)
            i += 1
        return "\n".join(result)

    def _finalize_answer(self, state: ConversationState) -> str:
        # P0: Always use academic_question (never use slot reply)
        ctx = state.context or {}
        uq = (ctx.get("academic_question") or "").strip()

        if not uq:
            if hasattr(state, "get_last_retrieval_query"):
                uq = (state.get_last_retrieval_query() or "").strip()
            else:
                uq = (state.last_retrieval_query or "").strip()

        uq = uq or getattr(conf, "DEFAULT_RETRIEVAL_FALLBACK_QUERY",
                           "กฎหมายร้านอาหาร ใบอนุญาต ภาษี VAT จดทะเบียน สุขาภิบาล ประกันสังคม")

        prompt = self._build_final_prompt(state, user_question=uq)

        # Fix 6: Collect allowed URLs from the injected link sections so we can strip any
        # hallucinated URLs the LLM generates that are NOT from the approved source list.
        # Collect all URLs present in the prompt — any URL the LLM outputs that wasn't in the
        # prompt is a hallucination (fabricated). Using the whole prompt avoids the fragile
        # section-tracking heuristic that could miss URLs when a short line resets the state.
        _allowed_urls: set = {
            u.rstrip(".,;)")
            for u in re.findall(r"https?://[^\s\n，。、\"']+", prompt)
        }

        try:
            decision = self._call_llm_json(prompt, state=state)
        except Exception as _fa_err:
            _LOG.error("[Academic] _finalize_answer: LLM call failed: %s", _fa_err)
            decision = {}

        _ex_raw = decision.get("execution") or {}
        if isinstance(_ex_raw, str):
            try:
                _ex_raw = json.loads(_ex_raw)
            except Exception:
                _ex_raw = {}
        ex = _ex_raw if isinstance(_ex_raw, dict) else {}
        ans = (ex.get("answer") or "").strip()
        if not ans:
            ans = "ขอโทษครับ ตอนนี้ยังไม่พบข้อมูลในเอกสารที่เกี่ยวข้อง"
        ans = self._fix_line_wrapping(ans)

        # Fix 6 (continued): Remove hallucinated URLs from the answer — any URL not in _allowed_urls.
        if _allowed_urls:
            def _strip_hallucinated_url(m: re.Match) -> str:
                u = m.group(0).rstrip(".,;)")
                if u in _allowed_urls:
                    return u
                # Also allow truncated forms: LLM sometimes shortens a known URL
                if any(allowed.startswith(u) for allowed in _allowed_urls):
                    return u
                return ""
            ans = re.sub(r"https?://[^\s\n，。、\"']+", _strip_hallucinated_url, ans)
        else:
            # No injected links at all — remove ALL URLs to prevent hallucination
            ans = re.sub(r"https?://[^\s\n，。、\"']+", "", ans)

        # Post-process: strip "Website"/"เว็บไซต์" prefix from 📄/📖 header lines (same as Practical)
        if '📄' in ans or '📖' in ans:
            ans = re.sub(
                r'(?m)^([ \t]*📄️?[ \t]*)(?:Website|เว็บไซต์)[ \t]+',
                r'\1', ans, flags=re.IGNORECASE,
            )
            ans = re.sub(
                r'(?m)^([ \t]*📖️?[ \t]*)(?:Website|เว็บไซต์)[ \t]+',
                r'\1', ans, flags=re.IGNORECASE,
            )

        # Strip hallucinated empty section headers (no content follows the heading)
        ans = re.sub(r"\n*📖\s*แหล่งข้อมูลอ้างอิง\s*$", "", ans, flags=re.MULTILINE).rstrip()
        ans = re.sub(r"\n*🌐\s*ช่องทางยื่นออนไลน์\s*$", "", ans, flags=re.MULTILINE).rstrip()
        # Strip any 🌐 section header that has no https:// URL within the next 5 lines.
        # LLM sometimes hallucinates a "🌐 เว็บไซต์ที่เกี่ยวข้อง" header by extracting URLs
        # from doc content even when SERVICE_LINKS was absent from the prompt.
        _ac_lines = ans.split('\n')
        _ac_out: list = []
        _ac_i = 0
        while _ac_i < len(_ac_lines):
            _ac_line = _ac_lines[_ac_i]
            if _ac_line.strip().startswith('🌐'):
                _ac_url_found = any(
                    'https://' in _ac_lines[_ac_j]
                    for _ac_j in range(_ac_i + 1, min(_ac_i + 6, len(_ac_lines)))
                )
                if _ac_url_found:
                    _ac_out.append(_ac_line)
                else:
                    # Consume following blank lines too
                    _ac_i += 1
                    while _ac_i < len(_ac_lines) and not _ac_lines[_ac_i].strip():
                        _ac_i += 1
                    continue
            else:
                _ac_out.append(_ac_line)
            _ac_i += 1
        ans = '\n'.join(_ac_out)

        cu = ex.get("context_update", {})
        if isinstance(cu, dict) and cu:
            state.context.update(cu)

        self._mark_done(state)

        # clean transient
        state.context["pending_options"] = {}
        state.context["pending_question"] = ""
        state.context.pop("resolved_selection", None)

        return ans

