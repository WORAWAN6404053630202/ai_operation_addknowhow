"""
Live, corpus-driven taxonomy resolution (2026-11, hardcoded-logic audit
follow-up — see persona_supervisor.py's _KW_OVERRIDE_LICENSE_TYPES comment
for the incident this generalizes).

Background: this bot was built against a human-curated Google Sheet
(service/data_loader.py reads license_type/main_topic/sub_topic verbatim
from spreadsheet columns a person typed — naturally stable). The corpus has
since shifted to primarily raw PDF uploads, where each document's taxonomy
fields are independently free-generated by an LLM call with zero existing-
vocabulary constraint (service/pdf_field_drafting.py / pdf_knowhow_drafting.
py never show the LLM the corpus's current taxonomy, and there is no
cross-document deduplication of generated labels). The same real-world
topic will keep accumulating differently-worded spellings over time, and
brand-new topics appear with zero advance warning — exactly what already
happened to persona_supervisor.py's hardcoded _KW_OVERRIDE_LICENSE_TYPES
(8/9 entries had drifted from the real corpus by the time anyone checked).

This module is the replacement shape: instead of hardcoding WHAT the valid
target values are, always ask the live corpus. Generalizes persona_
practical.py's _get_nonreg_main_topics (its own docstring: "Zero hardcoded
topic names... fetched live from Chroma, cached per-process, invalidated
via get_corpus_version()") into a shared, backend-agnostic utility both
persona_supervisor.py and persona_practical.py can use.

Backend-agnostic by construction: reads via getattr(vectorstore,
"_collection", None) + .get(...), the exact access shape _get_nonreg_
main_topics already uses — this works unmodified against both a real
Chroma collection and the ES facade (ESCompatVectorStore._collection is an
ESCompatCollection exposing the same .get() contract, confirmed elsewhere
this session's ES-migration work).
"""
from __future__ import annotations

import difflib
import logging
from typing import Dict, FrozenSet, List, Optional, Tuple

import conf

_LOG = logging.getLogger(__name__)

# (field, frozenset(data_type_filter items)) -> (corpus_version, sorted_values)
_live_values_cache: Dict[Tuple[str, FrozenSet], Tuple[int, List[str]]] = {}

# (normalized_hint, corpus_version) -> resolved value (or "" for "confirmed no match")
_llm_resolution_cache: Dict[Tuple[str, int], str] = {}


def _get_corpus_version() -> int:
    try:
        if getattr(conf, "USE_ELASTICSEARCH", False):
            from service.es_vector_store import get_corpus_version
        else:
            from service.local_vector_store import get_corpus_version
        return get_corpus_version()
    except Exception as _e:
        _LOG.debug("[live_taxonomy] get_corpus_version failed (%s) — treating as version 0", _e)
        return 0


def get_live_values(
    vectorstore, field: str, *, data_type_filter: Optional[dict] = None,
) -> List[str]:
    """Distinct non-empty values of `field` currently in the corpus, sorted
    longest-first (same convention as _get_nonreg_main_topics, so a
    substring check never matches a short value that's itself a substring
    of a longer, more specific one). Cached per-process, invalidated
    whenever get_corpus_version() changes — a direct-ingest write bumps
    this with no process restart, so the cache can't go stale silently."""
    _filter_key = frozenset((data_type_filter or {}).items())
    _cache_key = (field, _filter_key)
    _cv = _get_corpus_version()
    _cached = _live_values_cache.get(_cache_key)
    if _cached is not None and _cached[0] == _cv:
        return _cached[1]

    _values: set = set()
    if vectorstore is not None:
        _coll = getattr(vectorstore, "_collection", None)
        if _coll is not None:
            try:
                _where = {"data_type": data_type_filter} if data_type_filter else None
                _result = _coll.get(where=_where, include=["metadatas"]) if _where else _coll.get(include=["metadatas"])
                for _md in (_result.get("metadatas") or []):
                    _val = str((_md or {}).get(field) or "").strip()
                    if _val and _val.lower() not in ("nan", "none"):
                        _values.add(_val)
            except Exception as _e:
                _LOG.debug("[live_taxonomy] get_live_values(%r) fetch failed: %s", field, _e)

    _sorted = sorted(_values, key=len, reverse=True)
    _live_values_cache[_cache_key] = (_cv, _sorted)
    return _sorted


def get_live_license_types(vectorstore) -> List[str]:
    return get_live_values(vectorstore, "license_type")


def resolve_candidate(
    hint: str, live_values: List[str], *, fuzzy_threshold: float = 0.82,
) -> Tuple[Optional[str], str]:
    """Free, deterministic resolution of a loose keyword/concept hint
    against the live corpus values — no LLM call. Tier A only; callers
    should fall back to their own existing LLM classifier (fed this same
    live_values list, not a hardcoded one) when this returns (None, ...).

    fuzzy_threshold mirrors service.pdf_supersede_resolver.py's
    PDF_SUPERSEDE_IDENTITY_FUZZY_THRESHOLD (0.82) — same semantic job
    (deciding two differently-worded strings refer to the same real thing),
    same starting constant, not independently re-derived.

    Returns (value, "exact"|"fuzzy") on exactly one unambiguous match,
    or (None, "empty"|"ambiguous") otherwise.
    """
    if not hint or not live_values:
        return None, "empty"
    _hint = hint.strip()
    if not _hint:
        return None, "empty"

    if _hint in live_values:
        return _hint, "exact"

    _substring_matches = [v for v in live_values if _hint in v or v in _hint]
    if len(_substring_matches) == 1:
        return _substring_matches[0], "fuzzy"
    if len(_substring_matches) > 1:
        return None, "ambiguous"

    _scored = sorted(
        ((v, difflib.SequenceMatcher(None, _hint, v).ratio()) for v in live_values),
        key=lambda item: item[1], reverse=True,
    )
    if _scored and _scored[0][1] >= fuzzy_threshold:
        if len(_scored) == 1 or _scored[1][1] < _scored[0][1]:
            return _scored[0][0], "fuzzy"
        return None, "ambiguous"
    return None, "empty"


def get_cached_llm_resolution(hint: str) -> Optional[str]:
    """Process-level cache for LLM-resolved hint->value mappings, keyed on
    (normalized hint, corpus_version) rather than per-session — so every
    user typing the same keyword shares one resolution until the corpus
    actually changes, instead of each session re-paying the LLM call.
    Returns the resolved value, "" for a confirmed no-match, or None if
    never resolved (caller should still do the LLM call)."""
    _cv = _get_corpus_version()
    return _llm_resolution_cache.get((hint.strip().lower(), _cv))


def set_cached_llm_resolution(hint: str, resolved_value: Optional[str]) -> None:
    _cv = _get_corpus_version()
    _llm_resolution_cache[(hint.strip().lower(), _cv)] = resolved_value or ""
